"""Bring any air-quality dataset into the pipeline.

Maps the dataset onto the canonical schema (src/aqi/schema.py), writes it to data/processed/<name>/,
and generates configs/<name>.yaml with years and a train/val/test split that fit the dataset.

    python scripts/adapt_dataset.py data/raw/external/vopani --name vopani_delhi --city Delhi
    python scripts/run_pipeline.py --config configs/vopani_delhi.yaml
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from aqi.agents.schema_adapter import NotAQData, adapt, suggest_settings  # noqa: E402
from aqi.config import load_config  # noqa: E402
from aqi.ledger import Ledger  # noqa: E402
from aqi.llm import LLM  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("path", help="file or folder (CSV, CSV.GZ, Parquet, Excel)")
    ap.add_argument("--name", required=True, help="short name, used for the output folder and config")
    ap.add_argument("--city", help="keep only stations in this city")
    ap.add_argument("--no-llm", action="store_true", help="do not ask Claude about unrecognised columns")
    args = ap.parse_args()

    base = load_config()
    ledger = Ledger(f"adapt-{args.name}")
    llm = None if args.no_llm else LLM(base["llm"], ledger, "schema_adapter")
    try:
        frame, report = adapt(args.path, args.city, llm)
        settings = suggest_settings(frame, args.city)
    except NotAQData as e:
        print(f"This dataset can't be used: {e}")
        return 1

    out = ROOT / "data" / "processed" / args.name
    out.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(out / "canonical.parquet", index=False)
    report["suggested_settings"] = settings
    (out / "schema_report.json").write_text(json.dumps(report, indent=2))

    cfg = {k: v for k, v in base.items() if not k.startswith("_")}
    cfg["project"] = f"{args.name}-next-day-aqi"
    cfg["data"] = {**cfg["data"], "source": {"format": "canonical", "path": f"data/processed/{args.name}/canonical.parquet"},
                   "years": settings["years"]}
    cfg["split"] = {**cfg["split"], **settings["split"]}
    cfg["profiler"] = {**cfg["profiler"], "min_years_meeting_coverage": settings["min_years_meeting_coverage"]}
    cfg["features"]["groups"] = {**cfg["features"]["groups"], **settings["groups"]}
    header = (f"# Generated by scripts/adapt_dataset.py from {args.path}"
              f"{f' (city: {args.city})' if args.city else ''}.\n# Schema mapping: data/processed/{args.name}/schema_report.json\n")
    (ROOT / "configs" / f"{args.name}.yaml").write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))

    print(f"\n{report['stations']} stations · {report['rows']:,} {report['granularity']} rows · {report['start']} → {report['end']}")
    for m in report["mappings"]:
        print(f"  {m['source']:<22} → {m['canonical']:<8} {m['conversion']}  [{m['by']}]")
    for i in report["ignored"]:
        print(f"  {i['column']:<22} ✕ {i['reason']}")
    for w in report["warnings"]:
        print(f"  ! {w}")
    s = settings["split"]
    print(f"\nSplit: train {s['train'][0][:4]}–{s['train'][1][:4]} · val {s['val'][0][:4]}–{s['val'][1][:4]} · test {s['test'][0][:4]}")
    print(f"Wrote data/processed/{args.name}/ and configs/{args.name}.yaml")
    print(f"Run it:  python scripts/run_pipeline.py --config configs/{args.name}.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
